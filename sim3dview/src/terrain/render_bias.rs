//! 地表に貼り付くものを、地表からわずかに持ち上げる高さ(メートル)の一覧(Zファイティング対策)。
//!
//! 地表に貼り付くもの(図形・航跡・マーカー・覆域)は、地形メッシュ(粗いLODを含む)と同じ深度になると
//! 縞模様(Zファイティング)になったり、粗いLODの地形の高さのずれで地面に埋まって見えなくなったりする。
//! そこで、地表の標高にこの高さを足して置く。値は種類ごとに実機で調整したもので、地表に置くものの
//! 大きさ・見え方が違うので揃えていない。
//!
//! シェーダー側にも、同じ目的の深度のバイアスがある(この一覧とは別に、対で調整する):
//! `draw.wgsl`の`LINE_DEPTH_BIAS`(線を面より手前に)・`BILLBOARD_DEPTH_BIAS`(マーカーを距離に比例して手前に)・`billboard_depth`(ビルボードを、足元の地面の面より手前に。
//! 地面すれすれのシンボルの下半分が埋まらないように)、
//! `terrain.wgsl`の`WATER_DEPTH_MARGIN_M`(水域の面を視線方向へずらす量)。

/// 作図の図形・線(`AboveGround`)。
pub const DRAWING_M: f64 = 15.0;
/// 航跡(地表基準の高度のもの)と、その高度線の足元。
pub const TRACK_M: f64 = 25.0;
/// レーダー観測点のマーカー(ピン)の先端。
pub const MARKER_M: f64 = 25.0;
/// 覆域ドームの面。遮蔽される方角ではドームの境界が定義上ちょうど地形の表面に接するので、
/// 全体を一律に少し持ち上げてZファイティングを避ける。
pub const DOME_M: f64 = 20.0;
/// 2Dの覆域表示。深度テストはしないが、真上からの正射影の奥行きの範囲に収めるため地表の高さに置く。
pub const COVERAGE_AREA_M: f64 = 20.0;
